using Lms.Contracts;
using Lms.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;

namespace Lms.IntegrationTests;

/// <summary>
/// Captures the SQL that EF Core actually generates for the four tagged domain queries (doc 01 §5:
/// "captured SQL committed per query"). Written to benchmark/artifacts/sql/captured-sql.md for review/commit.
/// Queries mirror the service code exactly.
/// </summary>
[Collection(StackCollection.Name)]
public sealed class CapturedSqlTests(StackFixture f)
{
    [Fact]
    public void Generated_sql_is_tagged_ordered_and_parameterized()
    {
        int[] ids = [3, 17, 42];
        var paging = new Paging(0, 100);
        using var cs = f.Catalog.Services.CreateScope();
        using var ms = f.Members.Services.CreateScope();
        using var ls = f.Loans.Services.CreateScope();
        var cat = cs.ServiceProvider.GetRequiredService<CatalogDbContext>();
        var mem = ms.ServiceProvider.GetRequiredService<MembersDbContext>();
        var loa = ls.ServiceProvider.GetRequiredService<LoansDbContext>();

        var captured = new Dictionary<string, string>
        {
            [QueryIds.BooksPage] = cat.Books.TagWith("q:" + QueryIds.BooksPage).OrderBy(b => b.BookId).Skip(paging.Offset).Take(paging.Limit)
                .Select(b => new BookDto(b.BookId, b.Title, b.Authors, b.Description, b.Category, b.Publisher, b.Price, b.PublishMonth, (int?)b.PublishYear)).ToQueryString(),
            [QueryIds.BooksByIds] = cat.Books.TagWith("q:" + QueryIds.BooksByIds).Where(b => ids.Contains(b.BookId)).OrderBy(b => b.BookId)
                .Select(b => new BookDto(b.BookId, b.Title, b.Authors, b.Description, b.Category, b.Publisher, b.Price, b.PublishMonth, (int?)b.PublishYear)).ToQueryString(),
            [QueryIds.MembersPage] = mem.Members.TagWith("q:" + QueryIds.MembersPage).OrderBy(m => m.MemberId).Skip(paging.Offset).Take(paging.Limit)
                .Select(m => new MemberDto(m.MemberId, m.FirstName, m.LastName, m.Email, m.PhoneNumber, m.Address)).ToQueryString(),
            [QueryIds.LoansByMembers] = loa.Loans.TagWith("q:" + QueryIds.LoansByMembers).Where(l => ids.Contains(l.MemberId)).OrderBy(l => l.MemberId).ThenBy(l => l.LoanId)
                .Select(l => new LoanDto(l.LoanId, l.MemberId, l.BookId, l.LoanDate, l.ReturnDate, l.IsReturned)).ToQueryString(),
        };

        foreach (var (id, sql) in captured)
        {
            Assert.Contains("-- q:" + id, sql);
            Assert.Contains("ORDER BY", sql);
            Assert.DoesNotContain("SELECT *", sql);
        }

        var dir = FindBenchmarkDir();
        var outDir = Path.Combine(dir, "artifacts", "sql");
        Directory.CreateDirectory(outDir);
        File.WriteAllText(Path.Combine(outDir, "captured-sql.md"),
            "# Captured EF Core SQL (generated by CapturedSqlTests; EF Core 10.0.14, compatibility level 160)\n\n" +
            string.Join("\n", captured.Select(kv => $"## {kv.Key}\n\n```sql\n{kv.Value.Trim()}\n```\n")));
    }

    private static string FindBenchmarkDir()
    {
        var d = new DirectoryInfo(AppContext.BaseDirectory);
        while (d is not null && !File.Exists(Path.Combine(d.FullName, "LmsBenchmark.slnx"))) d = d.Parent;
        return d?.FullName ?? throw new DirectoryNotFoundException("benchmark root not found");
    }
}
